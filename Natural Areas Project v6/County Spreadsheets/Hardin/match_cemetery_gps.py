def normalize(name):
    n = name.lower()
    for s in ['cemetery', '(old)', '(new)', '(kenton)', '(north)', '(south)', '(west)', '(central)', '(east)']:
        n = n.replace(s, '')
    n = n.replace('/', ' ').replace('-', ' ').replace('.', ' ').replace("'", '')
    return ' '.join(n.split())

matched = []
no_match = []
ambiguous = []

for sid, our_name in unresolved:
    our_norm = normalize(our_name)
    candidates = []

    for osm_name, lat, lon in osm:
        osm_norm = normalize(osm_name)

        exact = (our_norm == osm_norm)
        variant = False

        # Roundhead old/new
        if 'roundhead' in our_norm and 'roundhead' in osm_norm:
            if ('old' in our_name.lower() and 'old' in osm_name.lower()) or \
               ('new' in our_name.lower() and 'new' in osm_name.lower()):
                variant = True

        # Henkle/Hinkle
        if ('henkle' in our_norm or 'hinkle' in our_norm) and 'hinkle' in osm_norm:
            variant = True

        # Seig/Sieg
        if 'seig' in our_norm and 'sieg' in osm_norm:
            variant = True

        # Yelverton
        if 'yelverton' in our_norm and 'yelverton' in osm_norm:
            variant = True

        # Huntersville/Huntsville
        if 'huntersville' in our_norm and 'huntersville' in osm_norm:
            variant = True

        # Ft McArthur / McArthur
        if 'ft' in our_norm and 'mcarthur' in our_norm and 'mcarthur' in osm_norm:
            variant = True

        if exact or variant:
            candidates.append((osm_name, lat, lon, 'exact' if exact else 'variant'))

    if len(candidates) == 1:
        c = candidates[0]
        matched.append((sid, our_name, c[0], c[1], c[2], c[3]))
        print(f'  MATCH  {sid} | {our_name:<38} -> {c[0]:<35} | {c[1]:.6f}, {c[2]:.6f} [{c[3]}]')
    elif len(candidates) > 1:
        ambiguous.append((sid, our_name, candidates))
        names = [c[0] for c in candidates]
        print(f'  AMBIG  {sid} | {our_name:<38} -> {names}')
    else:
        no_match.append((sid, our_name))

print(f'\nMatched:    {len(matched)}')
print(f'Ambiguous:  {len(ambiguous)}')
print(f'No match:   {len(no_match)}')
print('\nNo match list:')
for sid, name in no_match:
    print(f'  {sid} | {name}')
